import React, { useState } from 'react';
import { DetectionResult } from '../types';
import { formatConfidence, getSeverityColor, generateShareLink } from '../utils/mockDetection';
import { AlertTriangle, Download, Share2, Clipboard, CheckCircle } from 'lucide-react';

interface ResultsProps {
  result: DetectionResult;
  originalImage: string;
  onReset: () => void;
}

const Results: React.FC<ResultsProps> = ({ result, originalImage, onReset }) => {
  const [copied, setCopied] = useState(false);
  
  const copyToClipboard = () => {
    const link = generateShareLink(result);
    navigator.clipboard.writeText(link).then(() => {
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    });
  };
  
  const handleDownload = () => {
    // Create a text file with the results
    const disease = result.disease;
    if (!disease) return;
    
    const content = `
Rice Disease Analysis Results
----------------------------
Date: ${new Date().toLocaleDateString()}
Time: ${new Date().toLocaleTimeString()}

Disease: ${disease.name}
Confidence: ${formatConfidence(result.confidence)}
Severity: ${disease.severity.toUpperCase()}

Description:
${disease.description}

Symptoms:
${disease.symptoms.map(s => `- ${s}`).join('\n')}

Treatment Recommendations:
${disease.treatment.map(t => `- ${t}`).join('\n')}

Prevention:
${disease.prevention.map(p => `- ${p}`).join('\n')}

Generated by RiceGuard - Advanced Rice Disease Detection
    `.trim();
    
    const blob = new Blob([content], { type: 'text/plain' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `rice-disease-analysis-${new Date().toISOString().slice(0, 10)}.txt`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };
  
  if (!result.disease) {
    return (
      <div className="p-6 bg-white rounded-lg shadow-md text-center">
        <AlertTriangle className="h-12 w-12 text-yellow-500 mx-auto mb-4" />
        <h3 className="text-lg font-medium text-gray-900 mb-2">Analysis Failed</h3>
        <p className="text-gray-600 mb-4">
          We couldn't analyze this image. Please try again with a clearer image of a rice plant.
        </p>
        <button
          onClick={onReset}
          className="px-4 py-2 bg-green-600 text-white rounded-md hover:bg-green-700 transition-colors"
        >
          Try Again
        </button>
      </div>
    );
  }
  
  const disease = result.disease;
  const severityClass = getSeverityColor(disease.severity);
  
  return (
    <div className="bg-white rounded-lg shadow-md overflow-hidden">
      <div className="bg-green-700 p-4 text-white">
        <h2 className="text-xl font-bold">Analysis Results</h2>
        <p className="text-green-100 text-sm">
          {new Date().toLocaleDateString()} at {new Date().toLocaleTimeString()}
        </p>
      </div>
      
      <div className="p-6">
        <div className="flex flex-col md:flex-row gap-6">
          <div className="md:w-1/3">
            <div className="aspect-w-1 aspect-h-1 bg-gray-100 rounded-lg overflow-hidden">
              <img 
                src={originalImage} 
                alt="Analyzed rice plant"
                className="w-full h-full object-cover"
              />
            </div>
            
            <div className="mt-4 space-y-3">
              <div className="flex justify-between">
                <span className="text-sm text-gray-500">Confidence:</span>
                <span className="text-sm font-medium">{formatConfidence(result.confidence)}</span>
              </div>
              
              <div className="flex justify-between items-center">
                <span className="text-sm text-gray-500">Severity:</span>
                <span className={`text-xs font-medium px-2.5 py-0.5 rounded-full ${severityClass}`}>
                  {disease.severity.toUpperCase()}
                </span>
              </div>
              
              <div className="pt-4 flex flex-col gap-2">
                <button
                  onClick={handleDownload}
                  className="w-full flex items-center justify-center py-2 px-4 border border-gray-300 rounded-md shadow-sm text-sm font-medium text-gray-700 bg-white hover:bg-gray-50 transition-colors"
                >
                  <Download className="h-4 w-4 mr-2" />
                  Download Report
                </button>
                
                <button
                  onClick={copyToClipboard}
                  className="w-full flex items-center justify-center py-2 px-4 border border-gray-300 rounded-md shadow-sm text-sm font-medium text-gray-700 bg-white hover:bg-gray-50 transition-colors"
                >
                  {copied ? (
                    <>
                      <CheckCircle className="h-4 w-4 mr-2 text-green-500" />
                      Link Copied!
                    </>
                  ) : (
                    <>
                      <Share2 className="h-4 w-4 mr-2" />
                      Share Results
                    </>
                  )}
                </button>
                
                <button
                  onClick={onReset}
                  className="w-full flex items-center justify-center py-2 px-4 bg-green-600 text-white rounded-md hover:bg-green-700 transition-colors"
                >
                  Analyze Another Image
                </button>
              </div>
            </div>
          </div>
          
          <div className="md:w-2/3">
            <div className="mb-6">
              <h3 className="text-2xl font-bold text-gray-900 mb-2">{disease.name}</h3>
              <p className="text-gray-600">{disease.description}</p>
            </div>
            
            <div className="mb-6">
              <h4 className="text-lg font-semibold text-gray-900 mb-2">Symptoms</h4>
              <ul className="list-disc pl-5 space-y-1">
                {disease.symptoms.map((symptom, index) => (
                  <li key={index} className="text-gray-600">{symptom}</li>
                ))}
              </ul>
            </div>
            
            <div className="mb-6">
              <h4 className="text-lg font-semibold text-gray-900 mb-2">Treatment Recommendations</h4>
              <ul className="list-disc pl-5 space-y-1">
                {disease.treatment.map((item, index) => (
                  <li key={index} className="text-gray-600">{item}</li>
                ))}
              </ul>
            </div>
            
            <div>
              <h4 className="text-lg font-semibold text-gray-900 mb-2">Prevention</h4>
              <ul className="list-disc pl-5 space-y-1">
                {disease.prevention.map((item, index) => (
                  <li key={index} className="text-gray-600">{item}</li>
                ))}
              </ul>
            </div>
          </div>
        </div>
      </div>
    </div>
  );
};

export default Results;